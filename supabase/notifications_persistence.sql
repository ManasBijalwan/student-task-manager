-- Run once in the Supabase SQL Editor. The backend only performs DML at runtime.
ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS notify_me boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.task_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  task_id bigint REFERENCES public.tasks(id) ON DELETE SET NULL,
  event_key text NOT NULL,
  title text NOT NULL,
  message text NOT NULL,
  priority text NOT NULL CHECK (priority IN ('low', 'medium', 'high')),
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, event_key)
);

CREATE INDEX IF NOT EXISTS task_notifications_user_created_idx
  ON public.task_notifications (user_id, created_at DESC);
